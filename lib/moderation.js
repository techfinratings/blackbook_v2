var BANNED = [
  // 욕설·비하
  '씨발', '시발', '씨빨', '시빨', '씨팔', 'ㅅㅂ', 'ㅆㅂ', '병신', 'ㅂㅅ', '븅신',
  '지랄', 'ㅈㄹ', '좆', '존나', 'ㅈㄴ', '개새끼', '개색기', '새꺄', '썅',
  '미친놈', '미친년', '개년', '개놈', '니미', '니애미', '느금', '엿먹',
  '닥쳐', '꺼져라', '죽어버려',
  // 스팸·광고
  '카지노', '바카라', '토토사이트', '슬롯머신', '먹튀검증', '스포츠토토',
  '비아그라', '시알리스', '성인용품', '성인사이트', '조건만남', '출장안마', '출장마사지',
  '텔레그램상담', '오피', '유흥알바',
];

// 한글·영문·숫자만 남기고 소문자화 — 공백/기호 끼워넣기 우회 방지
function normalize(s) {
  return String(s || '').toLowerCase().replace(/[^0-9a-z가-힣ㄱ-ㆎ]/g, '');
}

// 걸리면 해당 단어, 아니면 null
function findBanned(text) {
  var raw = String(text || '').toLowerCase();
  var norm = normalize(text);
  for (var i = 0; i < BANNED.length; i++) {
    var w = BANNED[i];
    if (raw.indexOf(w) >= 0 || norm.indexOf(normalize(w)) >= 0) return w;
  }
  return null;
}

module.exports = { findBanned, BANNED };
